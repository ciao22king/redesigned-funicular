'use client';

import { useState } from 'react';
import Link from 'next/link';
import { signIn } from 'next-auth/react';
import { Nav } from '@/components/Nav';
import { Footer } from '@/components/Footer';
import { AudiencePicker, TonePicker } from '@/components/GenerateOptions';
import { QualityPanel } from '@/components/QualityPanel';
import { SAMPLES } from '@/lib/samples';
import { countWords } from '@/lib/skill';
import { DEFAULT_AUDIENCE, DEFAULT_TONE, type AudienceId, type ToneId } from '@/lib/audience';
import type { QualityReport } from '@/lib/quality';
import { track } from '@/lib/track';
import { Feedback } from '@/components/Feedback';

/**
 * The public demo. A visitor pastes material (or picks a sample), gets a real
 * skill preview, and only then is asked for a GitHub account. The preview is
 * generated by the same core as the signed-in flow.
 */
export default function DemoPage() {
  const [material, setMaterial] = useState(SAMPLES[0].raw);
  const [audience, setAudience] = useState<AudienceId>(DEFAULT_AUDIENCE);
  const [register, setRegister] = useState<ToneId>(DEFAULT_TONE);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [result, setResult] = useState<string | null>(null);
  const [quality, setQuality] = useState<QualityReport | null>(null);

  async function generate() {
    setBusy(true);
    setError(null);
    setResult(null);
    setQuality(null);
    track('funnel_submit');
    const startedAt = Date.now();
    try {
      const res = await fetch('/api/demo', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ mode: 'from-skills', sourceMaterial: material, audience, register }),
      });
      const data = (await res.json()) as {
        markdown?: string;
        error?: string;
        quality?: QualityReport;
      };
      if (!res.ok) throw new Error(data.error ?? 'Generation failed');
      setResult(data.markdown as string);
      setQuality(data.quality ?? null);
      track('generation_ms', { value: Date.now() - startedAt });
      track('funnel_result');
    } catch (e) {
      setError(e instanceof Error ? e.message : 'Unknown error');
    } finally {
      setBusy(false);
    }
  }

  return (
    <>
      <Nav />
      <main id="content" className="mx-auto max-w-4xl px-6 py-14">
        <p className="mb-3 font-mono text-xs uppercase tracking-[0.16em] text-[--accent]">
          Live demo · no account needed
        </p>

        <h1 className="font-display text-4xl font-semibold leading-[1.1] tracking-tight text-[--ink]">
          See the output before you sign in
        </h1>

        <p className="mt-5 max-w-prose text-[17px] text-[--ink-muted]">
          Paste a few notes, a transcript or a rough draft. The model turns it
          into a complete skill, exactly as it would after you sign in. The
          preview is free: no GitHub account required.
        </p>

        <div className="mt-8 flex flex-wrap gap-2">
          {SAMPLES.map((s) => (
            <button
              key={s.id}
              type="button"
              onClick={() => {
                setMaterial(s.raw);
                setResult(null);
                setError(null);
              }}
              className="rounded-full border border-[--line] bg-[--surface-raised] px-3.5 py-1.5 text-xs text-[--ink-muted] transition-colors hover:border-[--accent] hover:text-[--ink]"
            >
              Try: {s.label}
            </button>
          ))}
        </div>

        <div className="mt-6 space-y-6">
          <AudiencePicker value={audience} onChange={setAudience} />
          <TonePicker value={register} onChange={setRegister} />
        </div>

        <label className="mt-6 block">
          <span className="mb-2 block text-sm font-medium text-[--ink]">Your material</span>
          <textarea
            value={material}
            onChange={(e) => setMaterial(e.target.value)}
            rows={10}
            className="w-full resize-y rounded-xl border border-[--line] bg-[--surface-raised] px-4 py-3 text-sm text-[--ink] outline-none transition-colors placeholder:text-[--ink-muted]/60 focus:border-[--accent]"
            placeholder="Paste notes, a transcript, a draft..."
          />
        </label>

        <p className="mt-2 text-xs text-[--ink-muted]">
          Up to 4,000 characters in the demo. Sign in for longer material.
        </p>

        <div className="mt-6 rounded-xl border border-[--line] bg-[--surface-sunken] px-4 py-3 text-sm text-[--ink-muted]">
          Do not paste proprietary code, customer data, passwords or confidential
          documents.
        </div>

        <div className="mt-6">
          <button
            type="button"
            disabled={busy || material.trim().length < 60}
            onClick={() => void generate()}
            className="w-full rounded-xl bg-[--accent] px-6 py-3.5 font-medium text-white transition-opacity hover:opacity-90 disabled:cursor-not-allowed disabled:opacity-40 sm:w-auto"
          >
            {busy ? 'Generating...' : 'Generate a preview'}
          </button>
        </div>

        {error && (
          <div className="mt-6 rounded-xl border border-[oklch(70%_0.14_28)] bg-[oklch(95%_0.04_30)] px-4 py-3 text-sm text-[oklch(38%_0.13_28)]">
            {error}
          </div>
        )}

        {result && (
          <section className="mt-12 animate-fade-up">
            <div className="mb-4 flex items-baseline justify-between">
              <h2 className="font-display text-2xl font-semibold text-[--ink]">
                Your preview
              </h2>
              <span className="font-mono text-xs text-[--ink-muted]">
                {countWords(result)} words
              </span>
            </div>

            <pre className="max-h-[520px] overflow-auto rounded-xl border border-[--line] bg-[oklch(20%_0.02_50)] p-5 font-mono text-[12.5px] leading-relaxed text-[oklch(91%_0.03_70)]">
              {result}
            </pre>

            {quality && (
              <div className="mt-6">
                <QualityPanel report={quality} />
              </div>
            )}

            <div className="mt-6">
              <Feedback mode="demo" />
            </div>

            <div className="mt-6 rounded-xl border border-[--accent] bg-[--accent-soft] px-5 py-4">
              <p className="text-sm text-[--ink]">
                That is the real output. Sign in to edit it, download the{' '}
                <code className="font-mono text-[13px]">.md</code> file and publish
                it to the marketplace.
              </p>
              <button
                type="button"
                onClick={() => signIn('github')}
                className="mt-3 rounded-xl bg-[--accent] px-5 py-3 text-sm font-medium text-white transition-opacity hover:opacity-90"
              >
                Sign in with GitHub
              </button>
            </div>
          </section>
        )}

        <p className="mt-10 text-sm text-[--ink-muted]">
          Prefer to start from an idea?{' '}
          <Link href="/create/from-scratch" className="text-[--accent] underline underline-offset-2">
            Use the six-question wizard
          </Link>{' '}
          after signing in.
        </p>
      </main>
      <Footer />
    </>
  );
}
